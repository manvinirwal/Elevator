package models;

import java.util.ArrayList;
import java.util.List;

import models.enums.Direction;
import models.enums.ElevatorState;
import observers.ElevatorObserver;
import strategies.EnergyEfficientMovementStrategy;
import strategies.MovementStrategy;

public class Elevator {
    private int id;
    


    private MovementStrategy movementStrategy;

    private int capacity;

    /*
     * Current number of people/load inside the elevator.
     *
     * Overload is checked when the door is about to close /
     * elevator is about to start moving, not on every movement step.
     */
    private int currentLoad;

    private int currentFloor;

    /*
     * Direction represents the elevator's current movement direction.
     *
     * IDLE means the elevator currently has no direction of movement.
     */
    private Direction currentDirection;

    /*
     * Operating state of the elevator.
     *
     * OPERATING   -> elevator can serve requests
     * MAINTENANCE -> elevator is unavailable for passengers
     * EMERGENCY   -> elevator has been stopped because of emergency
     */
    private ElevatorState state;

    /*
     * Cabin panel is used by passengers inside the elevator
     * to select destinations and trigger emergency actions.
     */
    private ElevatorPanel elevatorPanel;

    /*
     * Each elevator maintains its own pending requests.
     *
     * This contains both:
     * 1. Hall requests assigned to this elevator by ElevatorController.
     * 2. Destination requests generated from ElevatorPanel.
     */
    private RequestQueue requestQueue;

   

    /*
     * Door belongs to the elevator because opening/closing the door
     * is part of the elevator's physical operation.
     */
    private Door door;

    private List<ElevatorObserver> observers;


    public Elevator(
            int id,
            int capacity,
            int currentFloor,
            Direction currentDirection,
            ElevatorState state,
            MovementStrategy movementStrategy
            ) {
        this.id = id;
        this.capacity = capacity;
        this.currentFloor = currentFloor;
        this.currentDirection = currentDirection;
        this.state = state;
        this.elevatorPanel = new ElevatorPanel(this);
        this.door = new Door();
        this.movementStrategy = movementStrategy;

        /*
         * RequestQueue is part of this elevator.
         * A request queue should not be shared between elevators.
         */
        this.requestQueue = new RequestQueue();

        this.currentLoad = 40;
        this.observers = new ArrayList<>();
    }

    public void addObserver(ElevatorObserver observer) {
        observers.add(observer);
}

    public void removeObserver(ElevatorObserver observer) {
        observers.remove(observer);
    }

    private void notifyObservers() {

        for (ElevatorObserver observer : observers) {
            observer.update(this);
        }
    }


    /*
     * Handles both types of requests:
     *
     * 1. Hall request assigned by ElevatorController.
     * 2. Destination request generated by ElevatorPanel.
     *
     * The elevator does not care where the request came from.
     * Once assigned to it, it simply adds the request to its queue.
     */
    public void addRequest(Request request) {
        requestQueue.addRequest(request);
    }
    
    public void removeRequest(Request request) {
        requestQueue.removeRequest(request);
    }


    /*
     * Executes one movement tick.
     *
     * State determines whether the elevator is allowed to operate.
     *
     * For example:
     *
     * OPERATING   -> process movement
     * MAINTENANCE -> do nothing
     * EMERGENCY   -> do nothing
     *
     * The actual movement algorithm can  be delegated
     * to MovementStrategy.
     */
    


    //opening + closing the door happens within the same stop() tick. If overload is detected, stop() returns with the door open.
    //  On a later tick, we retry closing.
    public void stop() {

        // Elevator has arrived at a requested floor.
        door.open();

        // Passengers enter/exit here.
        // currentLoad may change.

        if (isOverloaded()) {
            // Keep the door open until overload is resolved.
            System.out.println("Elevator is overloaded reduce load");
            return;
        }

        door.close();
    }




    /*
     * Elevator does not contain the movement algorithm.
     *
     * It delegates movement to the configured strategy.
     */
    public void step() {

        // Elevator cannot operate in maintenance/emergency.
        if (state != ElevatorState.OPERATING) {
            return;
        }

        /*
        * If the door was left open during the previous stop because
        * of overload, try to close it before allowing movement.
        *
        * Closing the door and moving happen in different ticks.
        */
        if (door.isOpen()) {

            if (isOverloaded()) {
                System.out.println("Elevator is overloaded reduce load");
                return;
                
            }
            door.close();

            
        }

         /*
        * Door is closed.
        * The movement strategy decides whether to:
        *
        * 1. Stop at the current floor, or
        * 2. Move one floor.(after picking direction or reversing direction or in same diretion)
        */
        movementStrategy.step(this);
    }

    
    /*
     * Overload rule.
     *
     * We check this when elevator is about to move,
     * after passengers have entered/exited.
     */
    public boolean isOverloaded() {
        return currentLoad > capacity;
    }

    public void setRequestQueue(RequestQueue requestQueue) {
        this.requestQueue = requestQueue;
    }


    public int getCapacity() {
        return capacity;
    }

    public int getCurrentLoad() {
        return currentLoad;
    }

    public int getCurrentFloor() {
        return currentFloor;
    }

    public Direction getCurrentDirection() {
        return currentDirection;
    }

    public ElevatorState getState() {
        return state;
    }

    public ElevatorPanel getElevatorPanel() {
        return elevatorPanel;
    }
    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public Door getDoor() {
        return door;
    }

    public RequestQueue getRequestQueue() {
        return requestQueue;
    }

    public MovementStrategy getMovementStrategy() {
        return movementStrategy;
    }

    public void setCurrentFloor(int currentFloor) {
        this.currentFloor = currentFloor;
        notifyObservers();
    }

    public void setCurrentDirection(Direction currentDirection) {
        this.currentDirection = currentDirection;
        notifyObservers();
    }



    public void setState(ElevatorState state) {
        this.state = state;
        notifyObservers();
    }
   
    public void enableEnergyEfficientMode(){
        MovementStrategy energyEfficientMovementStrategy = new EnergyEfficientMovementStrategy();
        setMovementStrategy(energyEfficientMovementStrategy);
    }
    public void setMovementStrategy(
            MovementStrategy movementStrategy) {
        this.movementStrategy = movementStrategy;
    }


    public void emergencyStop(){
        setState(ElevatorState.EMERGENCY_STOP);
    }
    public void triggerAlarm(){
        System.out.println("making sound");
    }


    /*
     * Passenger enters the elevator.
     */
    public void addLoad(int load) {
        currentLoad += load;
    }


    /*
     * Passenger leaves the elevator.
     */
    public void removeLoad(int load) {

        currentLoad -= load;

        if (currentLoad < 0) {
            currentLoad = 0;
        }
    }
    

    


}